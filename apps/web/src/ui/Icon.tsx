export type IconName = keyof typeof GLYPHS;

export function Icon({ name, size = 16, className = '' }: { name: IconName; size?: number; className?: string }) {
  const rows = GLYPHS[name];
  return (
    <svg width={size} height={size} viewBox="0 0 50 50" className={`shrink-0 ${className}`} aria-hidden fill="currentColor">
      {rows.flatMap((row, y) =>
        [...row].map((c, x) => (c === '#' ? <rect key={`${x}-${y}`} x={x * 10 + 1} y={y * 10 + 1} width="8" height="8" rx="2.2" /> : null)),
      )}
    </svg>
  );
}
